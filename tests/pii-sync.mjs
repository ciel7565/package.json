#!/usr/bin/env node
// =============================================================================
// tests/pii-sync.mjs — ONE rule list for the personal-information mask (kid safety, CONTRACT §12.4).
//
// The client engine in src/game/60-social.js (between "// >>> PII ENGINE" and "// <<< PII ENGINE") is the source
// of truth for the ordered rules. This script evaluates that block in Node and writes the compiled pattern list to
// server/lib/pii-rules.json, which server/lib/ChatFilter.php loads — so the server masks with exactly the same
// patterns (the fold and the two predicates are mirrored by hand in ChatFilter.php and are checked by the shared
// vectors in tests/pii-vectors.json).
//
//   node tests/pii-sync.mjs           regenerate server/lib/pii-rules.json
//   node tests/pii-sync.mjs --check   exit 1 when the JSON is out of date (run by tests/server-e2e.mjs)
// =============================================================================
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src/game/60-social.js');
const OUT = path.join(ROOT, 'server/lib/pii-rules.json');

/** evaluate the engine block of 60-social.js and return {rules, engine} */
export function loadEngine() {
  const code = fs.readFileSync(SRC, 'utf8');
  const a = code.indexOf('// >>> PII ENGINE'), b = code.indexOf('// <<< PII ENGINE');
  if (a < 0 || b < a) throw new Error('PII ENGINE markers not found in src/game/60-social.js');
  const body = code.slice(code.lastIndexOf('\n', a), b);
  const G = { log: { warn: (...x) => { throw new Error('PII engine warning: ' + x.join(' ')); } } };
  // eslint-disable-next-line no-new-func -- test tooling only (never shipped): runs the game's own engine block
  const engine = new Function('G', `${body}\nreturn { PII_SRC, maskPIIInfo, nicknameLooksPersonal };`)(G);
  const rules = engine.PII_SRC.map(([name, src, flags, pred]) => {
    // a PCRE pattern is delimited by "/": escape the ones that are not already escaped
    const pcre = src.replace(/(^|[^\\])((?:\\\\)*)\//g, '$1$2\\/');
    new RegExp(src, flags); // must compile in JS
    return { name, src: pcre, flags: flags.replace('g', ''), pred: pred ? pred.name : null };
  });
  return { rules, engine };
}

export function rulesJson() {
  const { rules } = loadEngine();
  return JSON.stringify({
    about: 'GENERATED by tests/pii-sync.mjs from src/game/60-social.js (PII ENGINE) — do not edit by hand. Loaded by server/lib/ChatFilter.php.',
    version: 1,
    rules,
  }, null, 1) + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = rulesJson();
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (cur !== next) { console.error('✖ server/lib/pii-rules.json is out of date — run: node tests/pii-sync.mjs'); process.exit(1); }
    console.log('✔ server/lib/pii-rules.json matches the client PII engine');
  } else {
    fs.writeFileSync(OUT, next);
    console.log(`✔ wrote ${path.relative(ROOT, OUT)} (${JSON.parse(next).rules.length} rules)`);
  }
}
